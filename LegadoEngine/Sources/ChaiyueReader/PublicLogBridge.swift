#if os(iOS)
// ⭐⭐⭐⭐⭐ **柴阅阅读器的【日志出口】**（2026-11-28 · 真机「点开始阅读闪退」取证）⭐⭐⭐⭐⭐
//
// ⚠️⚠️⚠️ **为什么需要这个** ⭐⭐⭐：
//   真机症状：**点「开始阅读」直接闪退**，而且**文字书和漫画书都崩**（两种都崩 ⇒ 共因在共用的那一层）⭐⭐⭐
//   ⇒ 但 **iOS 的崩溃日志（.ips）在设备上很难取到** ⇒ 没法定位到那一行 ⭐⭐⭐
//   ⇒ **正解**：在阅读器启动链的**每个阶段**都打一条日志 ⇒ 崩在哪一步一目了然 ⭐⭐⭐
//
// ⭐⭐⭐ **为什么不直接把日志出口放在宿主协议里**（`ChaiyueReaderLibrary`）：
//   ⇒ 那是 `public protocol` ⇒ 加成员 ⇒ **Swift 6 的 actor 隔离会连带打架**（协议要求 vs
//     宿主的 `@MainActor` 实现）⇒ ⇒ 风险大 ⭐⭐⭐
//   ⇒ **改成包内一个独立的日志桥** ⇒ 宿主注入一个 sink ⇒ 零协议改动 ⭐⭐⭐
//
// ⚠️ **与上游柴阅的 diff**：本文件是**我们新增的**（上游柴阅用自己的 `app.island`/日志体系）
//   ⇒ 不改动柴阅任何逻辑 ⇒ 只是多一个「往外说一句话」的出口 ⭐⭐⭐

import Foundation

/// 包 → 宿主的日志桥（宿主注入 `sink`，包内任何地方都能打日志）
@MainActor
public enum ChaiyueLogBridge {
    /// 宿主注入的落地口（宿主那边写进「引擎日志」面板 ⇒ **App 内就能看** ⇒ 不需要 .ips）⭐⭐⭐
    public static var sink: ((String) -> Void)?

    /// 打一条日志（没注入 sink 时静默 ⇒ 包内单独跑探针也不会炸）⭐⭐⭐
    public static func log(_ message: String) {
        sink?(message)
    }
}
#endif  // #if os(iOS)
